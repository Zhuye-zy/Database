);

CREATE TABLE patentdb.citation_category (
    category_code VARCHAR(10) NOT NULL,
    category_desc_en VARCHAR(200) NOT NULL,
    category_desc_cn VARCHAR(200) NOT NULL,
    source_standard VARCHAR(30) NOT NULL,
    note VARCHAR(200),
    CONSTRAINT pk_citation_category PRIMARY KEY (category_code)
);

CREATE TABLE patentdb.keyword (
    keyword_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    keyword_text VARCHAR(200) NOT NULL,
    lang_code CHAR(2) NOT NULL,
    source VARCHAR(50),
    CONSTRAINT pk_keyword PRIMARY KEY (keyword_id),
    CONSTRAINT uq_keyword_keyword_text_lang_code UNIQUE (keyword_text, lang_code)
);

CREATE TABLE patentdb.ipc_techn_field (
    ipc_maingroup_symbol VARCHAR(8) NOT NULL,
    techn_field_nr SMALLINT NOT NULL,
    techn_sector VARCHAR(50),
    techn_field VARCHAR(50),
    CONSTRAINT pk_ipc_techn_field PRIMARY KEY (ipc_maingroup_symbol)
);

CREATE TABLE patentdb.patent (
    patent_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dataset_id BIGINT NOT NULL,
    appln_auth CHAR(2) NOT NULL,
    appln_nr VARCHAR(30) NOT NULL,
    appln_kind VARCHAR(2) NOT NULL,
