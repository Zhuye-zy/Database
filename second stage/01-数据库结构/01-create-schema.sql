BEGIN;
CREATE SCHEMA IF NOT EXISTS patentdb;
SET search_path TO patentdb, public;

CREATE TABLE patentdb.dataset (
    dataset_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dataset_code VARCHAR(20) NOT NULL,
    dataset_name_cn VARCHAR(200) NOT NULL,
    dataset_name_en VARCHAR(200),
    office_code CHAR(2) NOT NULL,
    data_category VARCHAR(20) NOT NULL,
    file_format VARCHAR(20) NOT NULL,
    manual_ref VARCHAR(500),
    description TEXT,
    CONSTRAINT pk_dataset PRIMARY KEY (dataset_id),
    CONSTRAINT uq_dataset_dataset_code UNIQUE (dataset_code)
);

CREATE TABLE patentdb.country_office (
    ctry_code CHAR(2) NOT NULL,
    iso_alpha3 CHAR(3),
    st3_name VARCHAR(100) NOT NULL,
    name_cn VARCHAR(100),
    organisation_flag CHAR(1) NOT NULL,
    continent VARCHAR(25),
    is_epo_member CHAR(1) NOT NULL,
    is_eu_member CHAR(1) NOT NULL,
    discontinued CHAR(1) NOT NULL,
    CONSTRAINT pk_country_office PRIMARY KEY (ctry_code),
    CONSTRAINT uq_country_office_iso_alpha3 UNIQUE (iso_alpha3)
);

CREATE TABLE patentdb.language (
    lang_code CHAR(2) NOT NULL,
    name_en VARCHAR(50) NOT NULL,
    name_cn VARCHAR(50),
    CONSTRAINT pk_language PRIMARY KEY (lang_code)
);

CREATE TABLE patentdb.kind_code (
    office_code CHAR(2) NOT NULL,
    kind_code VARCHAR(2) NOT NULL,
    kind_description_en VARCHAR(200) NOT NULL,
    kind_description_cn VARCHAR(200) NOT NULL,
    publication_level CHAR(1),
    is_grant CHAR(1) NOT NULL,
    note VARCHAR(200),
    CONSTRAINT pk_kind_code PRIMARY KEY (office_code, kind_code)
);

CREATE TABLE patentdb.application_type (
    appl_type_code VARCHAR(20) NOT NULL,
    appl_type_name_en VARCHAR(100) NOT NULL,
    appl_type_name_cn VARCHAR(100) NOT NULL,
    ipr_type CHAR(2),
    CONSTRAINT pk_application_type PRIMARY KEY (appl_type_code)
);

CREATE TABLE patentdb.classification_scheme (
    scheme_code VARCHAR(10) NOT NULL,
    scheme_name_en VARCHAR(100) NOT NULL,
    scheme_name_cn VARCHAR(100) NOT NULL,
    authority CHAR(2),
    symbol_format VARCHAR(100),
    is_hierarchical CHAR(1) NOT NULL,
    CONSTRAINT pk_classification_scheme PRIMARY KEY (scheme_code)
);

CREATE TABLE patentdb.legal_event_code (
    event_auth CHAR(2) NOT NULL,
    event_code VARCHAR(4) NOT NULL,
    event_impact CHAR(1),
    event_descr VARCHAR(250) NOT NULL,
    event_descr_orig VARCHAR(250),
    event_category_code CHAR(1),
    event_category_title VARCHAR(100),
