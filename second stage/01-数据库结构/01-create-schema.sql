-- Enforce person ISA: each person must have exactly one matching subtype.
CREATE OR REPLACE FUNCTION patentdb.check_person_isa() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_person_id BIGINT;
    v_type CHAR(1);
    v_natural BOOLEAN;
    v_org BOOLEAN;
BEGIN
    v_person_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.person_id ELSE NEW.person_id END;
    SELECT person_type INTO v_type FROM patentdb.person WHERE person_id = v_person_id;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT EXISTS (SELECT 1 FROM patentdb.natural_person WHERE person_id = v_person_id),
           EXISTS (SELECT 1 FROM patentdb.organization WHERE person_id = v_person_id)
      INTO v_natural, v_org;
    IF (v_type = 'N' AND v_natural AND NOT v_org) OR (v_type = 'L' AND v_org AND NOT v_natural) THEN
        RETURN NULL;
    END IF;
    RAISE EXCEPTION 'person % must have exactly one subtype matching person_type %', v_person_id, v_type;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_person_isa AFTER INSERT OR UPDATE OR DELETE ON patentdb.person DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION patentdb.check_person_isa();
CREATE CONSTRAINT TRIGGER ct_natural_person_isa AFTER INSERT OR UPDATE OR DELETE ON patentdb.natural_person DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION patentdb.check_person_isa();
CREATE CONSTRAINT TRIGGER ct_organization_isa AFTER INSERT OR UPDATE OR DELETE ON patentdb.organization DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION patentdb.check_person_isa();

COMMIT;
