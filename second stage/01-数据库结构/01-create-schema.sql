    appl_type_code VARCHAR(20),
    appln_filing_date DATE NOT NULL,
    appln_filing_date_raw CHAR(8),
    receiving_office CHAR(2),
    appln_lang CHAR(2),
    int_phase CHAR(1) NOT NULL,
    reg_phase CHAR(1) NOT NULL,
    nat_phase CHAR(1) NOT NULL,
