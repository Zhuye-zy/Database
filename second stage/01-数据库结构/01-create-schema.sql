    botanic_variety VARCHAR(200),
    CONSTRAINT pk_patent PRIMARY KEY (patent_id),
    CONSTRAINT uq_patent_appln_business_key UNIQUE (appln_auth,appln_nr,appln_kind)
);

CREATE TABLE patentdb.publication (
    publication_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
