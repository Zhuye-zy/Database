CREATE TABLE patentdb.abstract (
    abstract_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    publication_id BIGINT NOT NULL,
    lang_code CHAR(2) NOT NULL,
    abstract_text TEXT NOT NULL,
    data_format VARCHAR(20),
